import {
  Check,
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  OneToMany,
  PrimaryColumn,
  type Relation,
} from 'typeorm';
import type { StructuredIngredientData } from '@/modules/ingredient-intelligence/models/structured-ingredient-data.model.js';
import { ModelVersion } from '@/modules/model-registry/entities/model-version.entity.js';
import { User } from '@/modules/users/entities/user.entity.js';
import { AnalysisStatus } from '../constants/scans.constants.js';
import { Detection } from './detection.entity.js';

@Entity()
@Index(['userId', 'createdAt', 'id'])
@Check(`"image_width" > 0 AND "image_height" > 0`)
@Check(`"latency_ms" >= 0`)
export class Scan {
  // Generated by the service before insert so detections and provenance ids exist up front.
  @PrimaryColumn({ type: 'uuid' })
  id!: string;

  @Column({ type: 'uuid' })
  userId!: string;

  @ManyToOne(() => User, { onDelete: 'CASCADE' })
  @JoinColumn()
  user!: Relation<User>;

  @Index()
  @Column({ type: 'text' })
  modelVersionId!: string;

  @ManyToOne(() => ModelVersion, { onDelete: 'RESTRICT' })
  @JoinColumn()
  modelVersion!: Relation<ModelVersion>;

  @Column({ type: 'integer' })
  imageWidth!: number;

  @Column({ type: 'integer' })
  imageHeight!: number;

  @Column({ type: 'integer' })
  latencyMs!: number;

  @Column({ type: 'text' })
  rulesVersion!: string;

  @Column({ type: 'text', nullable: true })
  promptVersion!: string | null;

  @Column({ type: 'jsonb' })
  result!: StructuredIngredientData;

  @Column({
    type: 'enum',
    enum: AnalysisStatus,
    enumName: 'scan_analysis_status',
  })
  analysisStatus!: AnalysisStatus;

  @Column({ type: 'jsonb', nullable: true })
  analysis!: Record<string, unknown> | null;

  @OneToMany(() => Detection, (detection) => detection.scan)
  detections!: Relation<Detection[]>;

  // Millisecond precision so a history cursor built from a JS Date matches the stored value exactly.
  @Index()
  @CreateDateColumn({ type: 'timestamptz', precision: 3 })
  createdAt!: Date;
}
